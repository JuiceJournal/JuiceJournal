window.LocaleOptions.forEach(function addLocaleFile(option) {
  if (!window.Translations[option.code]) {
    var locale = window.LocaleTranslations && window.LocaleTranslations[option.code];
    window.Translations[option.code] = Object.assign({}, locale && locale.ui);
  }
});

Object.keys(window.Translations.en).forEach(function ensureEnglishFallbackCoverage(key) {
  Object.keys(window.Translations).forEach(function applyFallback(localeCode) {
    if (!window.Translations[localeCode][key]) {
      window.Translations[localeCode][key] = window.Translations.en[key] || key;
    }
  });
});

/**
 * Get translation for a key
 */
window.t = function(key, values) {
  const lang = (window._appState && window._appState.language) || 'en';
  const template = window.Translations[lang]?.[key] || window.Translations['en']?.[key] || key;
  const tokens = values || {};
  return String(template).replace(/\{(\w+)\}/g, function(match, token) {
    return Object.prototype.hasOwnProperty.call(tokens, token) ? String(tokens[token]) : match;
  });
};

/**
 * Apply translations to all elements with data-i18n attributes
 */
window.applyTranslations = function() {
  var lang = (window._appState && window._appState.language) || 'en';
  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    var key = el.getAttribute('data-i18n');
    var text = window.t(key);
    el.textContent = text;
    // A name kept in English inside another language keeps English capitals: under tr, uppercase turns i into a
    // dotted capital, which is right for Turkish words only.
    if (lang !== 'en' && text === window.Translations.en[key]) {
      el.setAttribute('lang', 'en');
    } else {
      el.removeAttribute('lang');
    }
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el) {
    el.placeholder = window.t(el.getAttribute('data-i18n-placeholder'));
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(function(el) {
    el.setAttribute('aria-label', window.t(el.getAttribute('data-i18n-aria')));
  });
  document.querySelectorAll('[data-i18n-title]').forEach(function(el) {
    el.title = window.t(el.getAttribute('data-i18n-title'));
  });
  // The page's language picks the fallback font for scripts the bundled fonts lack, and the case mapping of uppercase
  // labels: under tr an i becomes a dotted capital, as Turkish writes it.
  document.documentElement.lang = lang;
};

window.getSupportedLocales = function() {
  return window.LocaleOptions;
};
